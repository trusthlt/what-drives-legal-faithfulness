import atexit as _atexit
import time as _time


def _register_runtime_timer():
    _script_start = _time.perf_counter()

    def _print_runtime():
        elapsed = _time.perf_counter() - _script_start
        print(f"\nElapsed time: {elapsed:.2f} seconds ({elapsed / 60:.2f} minutes)")

    _atexit.register(_print_runtime)


if __name__ == "__main__":
    _register_runtime_timer()

import argparse
import json
import os


def compute_ee_importance(
    explanation_importance_path,
    legal_concepts_path,
    out_path,
    include_original=True,
    normalize=False,
    max_importance=4.0,
):
    """
    Compute EE using concept-importance scores instead of binary mentions.

    For each concept c in a question:
      - optionally include the original explanation score for c
      - include only the counterfactual explanations generated by intervening on c
      - average the importance assigned to c across those explanations

    If normalize=True, scores are divided by max_importance so EE is in [0,1].
    Otherwise EE stays on the original importance scale.
    """

    with open(explanation_importance_path, "r", encoding="utf-8") as fh:
        importance_data = json.load(fh)

    with open(legal_concepts_path, "r", encoding="utf-8") as fh:
        concepts_data = json.load(fh)

    results = {}

    for title, block in importance_data.items():
        case_concepts = concepts_data.get(title)
        if not isinstance(case_concepts, dict):
            continue

        concepts = [
            k for k in case_concepts.keys()
            if k not in ("ORIGINAL QUESTION", "COUNTERFACTUALS")
        ]
        if not concepts:
            continue

        original_scores = block.get("original", {})
        if not isinstance(original_scores, dict):
            original_scores = {}

        ee_per_concept = {}

        for c in concepts:
            scores = []

            # Optional original explanation contribution
            if include_original:
                raw_score = original_scores.get(c, 0.0)
                try:
                    raw_score = float(raw_score)
                except (TypeError, ValueError):
                    raw_score = 0.0
                scores.append(raw_score)

            # Counterfactual explanations generated by changing concept c
            cf_list = block.get("counterfactuals", {}).get(c, [])
            if not isinstance(cf_list, list):
                cf_list = []

            for item in cf_list:
                if not isinstance(item, dict):
                    continue

                importance = item.get("importance", {})
                if not isinstance(importance, dict):
                    importance = {}

                raw_score = importance.get(c, 0.0)
                try:
                    raw_score = float(raw_score)
                except (TypeError, ValueError):
                    raw_score = 0.0

                scores.append(raw_score)

            total = len(scores)
            raw_sum = sum(scores)
            ee_raw = raw_sum / total if total > 0 else 0.0

            if normalize:
                ee = ee_raw / max_importance if max_importance > 0 else 0.0
            else:
                ee = ee_raw

            ee_per_concept[c] = {
                "EE": ee,
                "EE_raw": ee_raw,
                "importance_sum": raw_sum,
                "total": total,
                "scores": scores,
                "normalized": normalize,
                "max_importance": max_importance if normalize else None,
            }

        results[title] = ee_per_concept

    out_dir = os.path.dirname(out_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, ensure_ascii=False)

    print("Written EE importance results →", out_path)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--importance",
        required=True,
        help="JSON with original and counterfactual concept-importance scores.",
    )
    parser.add_argument(
        "--concepts",
        required=True,
        help="JSON with extracted legal concepts.",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="Where to write EE results.",
    )
    parser.add_argument(
        "--include-original",
        action="store_true",
        default=False,
        help="Include the original explanation importance score in the EE average.",
    )
    parser.add_argument(
        "--normalize",
        action="store_true",
        default=False,
        help="Normalize EE to [0,1] by dividing by --max-importance.",
    )
    parser.add_argument(
        "--max-importance",
        type=float,
        default=4.0,
        help="Maximum possible importance score, used only if --normalize is set.",
    )
    args = parser.parse_args()

    compute_ee_importance(
        explanation_importance_path=args.importance,
        legal_concepts_path=args.concepts,
        out_path=args.output,
        include_original=args.include_original,
        normalize=args.normalize,
        max_importance=args.max_importance,
    )